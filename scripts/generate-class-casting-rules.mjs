import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import ts from 'typescript'
import { createServer } from 'vite'
import { deriveClassCastingRegistry } from './lib/class-casting-source.mjs'

const root = process.argv.find((arg) => arg.startsWith('--data='))?.slice(7) ?? 'data'
const checking = process.argv.includes('--check')
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex')
// Preserve the canonical registry exactly while sharing repeated certificate/identity values.
function runtimeSource(registry) {
  const counts = new Map()
  const visit = (value) => {
    if (typeof value === 'string' && value.length > 8)
      counts.set(value, (counts.get(value) ?? 0) + 1)
    else if (Array.isArray(value)) value.forEach(visit)
    else if (value && typeof value === 'object') Object.values(value).forEach(visit)
  }
  visit(registry)
  const shared = new Map(
    [...counts].filter(([, count]) => count > 1).map(([value], index) => [value, `s${index}`]),
  )
  const encode = (value) => {
    if (typeof value === 'string') return shared.get(value) ?? JSON.stringify(value)
    if (Array.isArray(value)) return `[${value.map(encode).join(',')}]`
    if (value && typeof value === 'object')
      return `{${Object.entries(value)
        .map(
          ([key, item]) =>
            `${key === '__proto__' ? `[${JSON.stringify(key)}]` : JSON.stringify(key)}:${encode(item)}`,
        )
        .join(',')}}`
    return JSON.stringify(value)
  }
  return `// Generated by scripts/generate-class-casting-rules.mjs; do not edit.\n${[...shared].map(([value, name]) => `const ${name} = ${JSON.stringify(value)}\n`).join('')}\nconst registry = ${encode(registry)}\nexport default registry\n`
}
const format = (file, source) =>
  execFileSync(
    process.execPath,
    ['node_modules/@biomejs/biome/bin/biome', 'format', '--stdin-file-path', file],
    { input: source, encoding: 'utf8', windowsHide: true },
  )
// Ordinary generation verifies the separately reviewed finite meaning; it never refreshes this seed.
const seed = JSON.parse(fs.readFileSync('scripts/lib/class-casting-semantics.json', 'utf8'))
const server = await createServer({
  configFile: 'vite.config.e2e.ts',
  server: { middlewareMode: true, watch: null },
  appType: 'custom',
  logLevel: 'silent',
})
try {
  const api = await server.ssrLoadModule('/src/lib/5etools/optionalClassDeclarationStructure.ts')
  const { registry, files } = await deriveClassCastingRegistry(server, root, seed.targets)
  if (
    seed.version !== 1 ||
    api.optionalDeclarationDigest(registry) !== api.optionalDeclarationDigest(seed)
  )
    throw Error('Casting producer/parent/table meaning changed; independent assessment required')
  const helpers = new Set([
    'scripts/generate-class-casting-rules.mjs',
    'scripts/lib/class-casting-source.mjs',
    'scripts/lib/class-casting-semantics.json',
    'src/lib/5etools/classCastingStructure.ts',
    'src/lib/5etools/parsers/classes.ts',
    'src/lib/5etools/classData.ts',
    'package-lock.json',
    'src/lib/5etools/classCastingRuntime.generated.ts',
  ])
  const output = 'src/lib/5etools/classCastingRules.generated.json'
  const runtimeOutput = 'src/lib/5etools/classCastingRuntime.generated.ts'
  const runtimeBytes = format(runtimeOutput, runtimeSource(registry))
  const visit = (file) => {
    if (file === runtimeOutput) return
    if (!file.endsWith('.ts')) return
    for (const imported of ts.preProcessFile(fs.readFileSync(file, 'utf8')).importedFiles) {
      const name = imported.fileName
      const base = name.startsWith('@/')
        ? 'src/' + name.slice(2)
        : name.startsWith('.')
          ? path.posix.normalize(path.posix.join(path.posix.dirname(file), name))
          : undefined
      if (!base) continue
      const target = [base, base + '.ts', base + '/index.ts'].find(
        (file) => fs.existsSync(file) && fs.statSync(file).isFile(),
      )
      if (!target) throw Error('Unrecorded casting helper dependency: ' + base)
      // Parsing executes this output's source audit, whose evidence is excluded from the projections.
      if (target === output || helpers.has(target)) continue
      helpers.add(target)
      visit(target)
    }
  }
  for (const file of [...helpers]) visit(file)
  const manifest = {
    version: 1,
    upstream: execFileSync('git', ['-C', '.tmp/5etools-src', 'rev-parse', 'HEAD'], {
      encoding: 'utf8',
    }).trim(),
    inputs: files.map(({ source, file, bytes }) => ({ source, file, sha256: sha(bytes) })),
    helpers: [...helpers].sort().map((file) => ({
      file,
      sha256: sha(file === runtimeOutput ? runtimeBytes : fs.readFileSync(file)),
    })),
  }
  for (const [file, value] of [
    [output, registry],
    ['scripts/generated/class-casting-inputs.json', manifest],
  ]) {
    const bytes = format(file, JSON.stringify(value, null, 2) + '\n')
    if (checking) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== bytes)
        throw Error('Stale casting output: ' + file)
    } else fs.writeFileSync(file, bytes)
  }
  if (checking) {
    if (!fs.existsSync(runtimeOutput) || fs.readFileSync(runtimeOutput, 'utf8') !== runtimeBytes)
      throw Error('Stale casting output: ' + runtimeOutput)
  } else fs.writeFileSync(runtimeOutput, runtimeBytes)
  console.log(
    JSON.stringify({
      checked: checking,
      parents: registry.parents.length,
      producers: registry.producers.length,
      inputs: files.length,
      helpers: helpers.size,
    }),
  )
} finally {
  await server.close()
}
