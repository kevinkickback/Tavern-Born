/** Preserve the canonical registry exactly while sharing repeated certificate and identity strings. */
export function emitSharedRegistryModule(registry, generator) {
  const counts = new Map()
  const visit = (value) => {
    if (typeof value === 'string' && value.length > 2)
      counts.set(value, (counts.get(value) ?? 0) + 1)
    else if (Array.isArray(value)) value.forEach(visit)
    else if (value && typeof value === 'object') Object.values(value).forEach(visit)
  }
  visit(registry)
  const shared = new Map(
    [...counts].filter(([, count]) => count > 1).map(([value], index) => [value, 's' + index]),
  )
  const encode = (value) => {
    if (typeof value === 'string') return shared.get(value) ?? JSON.stringify(value)
    if (Array.isArray(value)) return '[' + value.map(encode).join(',') + ']'
    if (value && typeof value === 'object')
      return (
        '{' +
        Object.entries(value)
          .map(([key, item]) => {
            const property =
              key === '__proto__' ? '[' + JSON.stringify(key) + ']' : JSON.stringify(key)
            return property + ':' + encode(item)
          })
          .join(',') +
        '}'
      )
    return JSON.stringify(value)
  }
  const declarations = [...shared]
    .map(([value, name]) => 'const ' + name + ' = ' + JSON.stringify(value) + '\n')
    .join('')
  return (
    '// Generated by ' +
    generator +
    '; do not edit.\n' +
    declarations +
    '\nconst registry = ' +
    encode(registry) +
    '\nexport default registry\n'
  )
}
