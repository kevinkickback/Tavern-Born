/** Preserve the canonical registry exactly while sharing repeated certificate and identity strings. */
export function emitSharedRegistryModule(registry, generator, shareArrays = false) {
  const counts = new Map()
  const arrayCounts = new Map()
  const visit = (value) => {
    if (typeof value === 'string' && value.length > 2)
      counts.set(value, (counts.get(value) ?? 0) + 1)
    else if (Array.isArray(value)) {
      value.forEach(visit)
      if (shareArrays) {
        const key = JSON.stringify(value)
        if (key.length >= 64) arrayCounts.set(key, (arrayCounts.get(key) ?? 0) + 1)
      }
    } else if (value && typeof value === 'object') Object.values(value).forEach(visit)
  }
  visit(registry)
  const shared = new Map(
    [...counts].filter(([, count]) => count > 1).map(([value], index) => [value, 's' + index]),
  )
  const arrays = new Map(
    [...arrayCounts].filter(([, count]) => count > 1).map(([value], index) => [value, 'a' + index]),
  )
  const encode = (value, inlineArray = false) => {
    if (typeof value === 'string') return shared.get(value) ?? JSON.stringify(value)
    if (Array.isArray(value)) {
      const sharedArray = shareArrays && !inlineArray && arrays.get(JSON.stringify(value))
      return sharedArray || '[' + value.map((item) => encode(item)).join(',') + ']'
    }
    if (value && typeof value === 'object')
      return (
        '{' +
        Object.entries(value)
          .map(([key, item]) => {
            const property =
              key === '__proto__' ? '[' + JSON.stringify(key) + ']' : JSON.stringify(key)
            return property + ':' + encode(item)
          })
          .join(',') +
        '}'
      )
    return JSON.stringify(value)
  }
  const declarations = [...shared]
    .map(([value, name]) => 'const ' + name + ' = ' + JSON.stringify(value) + '\n')
    .join('')
  // Read-only certificates often carry identical field lists and source paths. Emit children
  // first so a repeated path may itself reuse any repeated lists it contains.
  const arrayDeclarations = [...arrays]
    .map(([value, name]) => 'const ' + name + ' = ' + encode(JSON.parse(value), true) + '\n')
    .join('')
  return (
    '// Generated by ' +
    generator +
    '; do not edit.\n' +
    declarations +
    arrayDeclarations +
    '\nconst registry = ' +
    encode(registry) +
    '\nexport default registry\n'
  )
}
